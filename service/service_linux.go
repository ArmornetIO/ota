package service

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// systemd on Linux. A user unit under ~/.config/systemd/user by default; a
// system unit under /etc/systemd/system when the caller asks for ScopeSystem.

// unitDir is where the unit file for this scope belongs.
func unitDir(scope Scope) (string, error) {
	if scope == ScopeSystem {
		return "/etc/systemd/system", nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("service: resolve home: %w", err)
	}
	return filepath.Join(home, ".config", "systemd", "user"), nil
}

// systemctl builds the systemctl invocation for this scope. Every call needs
// the --user flag or none of them do, and getting that inconsistent installs a
// unit in one domain and queries the other.
func systemctl(scope Scope, args ...string) *exec.Cmd {
	if scope == ScopeUser {
		args = append([]string{"--user"}, args...)
	}
	return exec.Command("systemctl", args...)
}

// unitFile renders the service unit.
//
// Restart=always with a delay rather than Restart=on-failure: a clean exit from
// the agent is still an agent that is no longer there, and the reason it exited
// (a revoked credential, an unreachable server) is usually temporary.
//
// ExecStart takes the binary and args already validated as free of line breaks
// — a unit file is line-oriented, and a break is the one injection that matters
// here.
func unitFile(s Spec) string {
	var b strings.Builder
	b.WriteString("# Generated by ota/service. Reinstall to change.\n")
	b.WriteString("[Unit]\n")
	fmt.Fprintf(&b, "Description=%s\n", s.Description)
	b.WriteString("After=network-online.target\n")
	b.WriteString("Wants=network-online.target\n\n")

	b.WriteString("[Service]\n")
	b.WriteString("Type=simple\n")
	fmt.Fprintf(&b, "ExecStart=%s\n", shJoin(append([]string{s.BinaryPath}, s.Args...)))
	if s.WorkingDir != "" {
		fmt.Fprintf(&b, "WorkingDirectory=%s\n", s.WorkingDir)
	}
	if s.LogPath != "" {
		// append: for a service that restarts, truncating on every start throws
		// away the log of the failure that caused the restart.
		fmt.Fprintf(&b, "StandardOutput=append:%s\n", s.LogPath)
		fmt.Fprintf(&b, "StandardError=append:%s\n", s.LogPath)
	}
	b.WriteString("Restart=always\n")
	b.WriteString("RestartSec=5\n\n")

	b.WriteString("[Install]\n")
	if s.Scope == ScopeSystem {
		b.WriteString("WantedBy=multi-user.target\n")
	} else {
		b.WriteString("WantedBy=default.target\n")
	}
	return b.String()
}

// shJoin quotes arguments for an ExecStart line. systemd parses it shell-like,
// so a path containing a space is otherwise read as two arguments, and it also
// expands %-specifiers, $VARIABLES and C escapes inside quotes. Each of those
// is escaped so an argument reaches the program exactly as the caller wrote it.
func shJoin(args []string) string {
	esc := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`)
	out := make([]string, len(args))
	for i, a := range args {
		out[i] = `"` + esc.Replace(a) + `"`
	}
	return strings.Join(out, " ")
}

// Install writes the unit, reloads systemd and enables the service so it comes
// back at boot. It is idempotent: an existing unit of the same name is
// overwritten and re-enabled.
func Install(s Spec) error {
	if err := s.Validate(); err != nil {
		return err
	}
	s = s.withDefaults()

	dir, err := unitDir(s.Scope)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("service: create %s: %w", dir, err)
	}
	// 0644: a unit file is read by systemd, carries no secret (the agent's
	// credentials live in the 0600 config it points at), and a mode systemd
	// cannot read is an install that silently does nothing.
	path := filepath.Join(dir, s.Name+".service")
	if err := os.WriteFile(path, []byte(unitFile(s)), 0o644); err != nil {
		return fmt.Errorf("service: write %s: %w", path, err)
	}

	if out, err := systemctl(s.Scope, "daemon-reload").CombinedOutput(); err != nil {
		return fmt.Errorf("service: systemctl daemon-reload: %w: %s", err, strings.TrimSpace(string(out)))
	}
	if out, err := systemctl(s.Scope, "enable", "--now", s.Name+".service").CombinedOutput(); err != nil {
		return fmt.Errorf("service: systemctl enable: %w: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// Uninstall stops, disables and removes the unit. A service that is already
// absent is not an error — uninstall is something a caller should be able to
// run twice.
func Uninstall(s Spec) error {
	s = s.withDefaults()

	dir, err := unitDir(s.Scope)
	if err != nil {
		return err
	}
	path := filepath.Join(dir, s.Name+".service")

	// Errors ignored: the unit may be present-but-stopped, or already gone, and
	// both are the state the caller asked for. The removal below is what decides
	// whether this worked.
	_ = systemctl(s.Scope, "disable", "--now", s.Name+".service").Run()

	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("service: remove %s: %w", path, err)
	}
	_ = systemctl(s.Scope, "daemon-reload").Run()
	return nil
}

// Query reports whether the unit is registered and up.
func Query(s Spec) (Status, error) {
	s = s.withDefaults()

	dir, err := unitDir(s.Scope)
	if err != nil {
		return Status{}, err
	}
	if _, err := os.Stat(filepath.Join(dir, s.Name+".service")); os.IsNotExist(err) {
		return Status{}, ErrNotInstalled
	}

	// is-active exits non-zero for every not-running state, so the exit code is
	// not the signal — the word it prints is.
	out, _ := systemctl(s.Scope, "is-active", s.Name+".service").CombinedOutput()
	state := strings.TrimSpace(string(out))
	return Status{Installed: true, Running: state == "active", Detail: state}, nil
}

// Start starts an installed unit.
func Start(s Spec) error { return unitVerb(s, "start") }

// Stop stops a unit without disabling it, so it still comes back at boot.
func Stop(s Spec) error { return unitVerb(s, "stop") }

// Restart stops and starts the unit in one systemd job, which is what a binary
// swap needs: systemd execs the new file on the start half.
func Restart(s Spec) error { return unitVerb(s, "restart") }

func unitVerb(s Spec, verb string) error {
	if err := s.Validate(); err != nil {
		return err
	}
	s = s.withDefaults()
	if out, err := systemctl(s.Scope, verb, s.Name+".service").CombinedOutput(); err != nil {
		return fmt.Errorf("service: systemctl %s: %w: %s", verb, err, strings.TrimSpace(string(out)))
	}
	return nil
}
